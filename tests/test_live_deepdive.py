@pytest.mark.unit
class TestRisks:
    def test_silence_is_reported_as_silence_not_as_safety(self):
        """"No risks found" must not read as "no risk"."""
        out = risks(analysis())
        assert len(out) == 1 and "这台机器读到的东西里没有" in out[0]

    def test_a_downtrend_is_named(self):
        falling = bars(start=120.0, step=-0.25)
        out = risks(analysis(bars=falling))
        assert any("下降结构" in r or "跌破" in r or "空头" in r for r in out)

    def test_earnings_inside_the_horizon_is_always_raised(self):
        out = risks(analysis(rec=Rec(), earnings=Earnings(days=8.0)))
        assert any("财报" in r and "穿过止损" in r for r in out)

    def test_earnings_outside_the_horizon_is_not_raised(self):
        out = risks(analysis(rec=Rec(), earnings=Earnings(days=90.0)))
        assert not any("穿过止损" in r for r in out)

    def test_an_unprofitable_company_is_named_as_one(self):
        f = Fundamentals(symbol="AAA", eps_trailing=-0.8)
        assert any("尚未盈利" in r for r in risks(analysis(fundamentals=f)))

    def test_negative_free_cash_flow_is_named(self):
        f = Fundamentals(symbol="AAA", eps_trailing=1.0, free_cashflow=-2.0e8)
        assert any("自由现金流为负" in r for r in risks(analysis(fundamentals=f)))

    def test_a_price_above_the_consensus_target_is_named(self):
        f = Fundamentals(symbol="AAA", eps_trailing=1.0, target_mean=50.0,
                         analysts=12.0)
        out = risks(analysis(fundamentals=f))
        assert any("高于卖方目标价均值" in r for r in out)

    def test_a_target_range_wider_than_its_mean_is_called_out_as_no_consensus(self):
        f = Fundamentals(symbol="AAA", eps_trailing=1.0, target_mean=100.0,
                         target_low=40.0, target_high=200.0, analysts=12.0)
        assert any("分歧极大" in r for r in risks(analysis(fundamentals=f)))

    def test_a_thin_book_is_named_because_the_report_assumed_it_could_fill(self):
        thin = bars(volume=20_000.0)
        assert any("流动性偏薄" in r for r in risks(analysis(bars=thin)))

    def test_a_bearish_headline_is_quoted_with_its_source(self):
        item = News("Company halts trial", lean="bearish", materiality=9)
        out = risks(analysis(news=[item]))
        assert any("Company halts trial" in r and "Wire" in r for r in out)

    def test_a_bearish_but_immaterial_headline_is_not_promoted_to_a_risk(self):
        item = News("Fund trims stake", lean="bearish", materiality=3)
        assert not any("Fund trims stake" in r for r in risks(analysis(news=[item])))


