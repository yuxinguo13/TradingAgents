@pytest.mark.unit
class TestBars:
    def test_a_short_history_is_not_ok_to_read(self):
        assert not bars(n=20).ok and bars(n=40).ok

    def test_the_facts_mapping_carries_what_the_horizon_modules_ask_for(self):
        got = bars().facts()
        for key in ("price", "sma200", "ret_12m", "off_high", "atr", "atr_pct",
                    "prev_high", "prev_low", "vol_ratio", "dollar_vol", "spark"):
            assert key in got

    def test_a_return_longer_than_the_history_is_absent_not_zero(self):
        assert math.isnan(bars(n=40).ret(252))

    def test_an_empty_frame_produces_empty_bars_rather_than_raising(self):
        got = deepdive.load_bars("AAA", "2026-08-31", loader=lambda s, d: None)
        assert len(got) == 0 and not got.ok

    def test_a_loader_that_raises_costs_the_bars_not_the_run(self):
        def boom(symbol, when):
            raise RuntimeError("network")

        assert len(deepdive.load_bars("AAA", "2026-08-31", loader=boom)) == 0


