@pytest.mark.unit
class TestRenderPage:
    def page(self, **kw):
        return render_page(analysis(**kw), report_date="2026-09-02",
                           data_date="2026-08-31", account_value=100_000.0,
                           back_link="../2026-09-02.md")

    def test_every_section_the_docstring_promises_is_present(self):
        text = self.page(rec=Rec())
        for heading in ("一、价格与图形", "二、这笔交易的算术", "四、消息面",
                        "五、反方观点与风险", "六、原始数据", "七、自己去查"):
            assert f"## {heading}" in text

    def test_the_chart_carries_the_three_levels_of_the_trade(self):
        text = self.page(rec=Rec())
        assert "← 止损" in text and "← 目标" in text and "← 参考" in text

    def test_the_bear_case_is_never_omitted(self):
        assert "## 五、反方观点与风险" in self.page()

    def test_the_two_sessions_are_both_named(self):
        text = self.page()
        assert "2026-08-31 收盘 → 面向 2026-09-02 开盘" in text

    def test_the_page_links_back_to_the_daily_report(self):
        assert "(../2026-09-02.md)" in self.page()

    def test_a_symbol_with_no_history_renders_an_absence_not_an_empty_chart(self):
        text = render_page(SymbolAnalysis(symbol="ZZZ"), report_date="2026-09-02")
        assert "没有价格数据" in text and "```text" not in text

    def test_the_raw_ohlcv_the_page_computed_from_is_printed(self):
        text = self.page()
        assert "| 日期 | 开 | 高 | 低 | 收 | 涨跌 | 成交量 |" in text

    def test_the_cost_matches_the_price_the_order_would_fill_at(self):
        """The daily table prices at the limit; two pages must not disagree."""
        text = self.page(rec=Rec())
        assert f"${Rec.limit_price * Rec.shares:,.2f}" in text

    def test_the_chart_read_says_out_loud_that_it_is_lagging(self):
        assert "滞后指标" in self.page()

    def test_news_items_are_linked_dated_and_sourced(self):
        text = self.page(news=[News("Something happened", link="https://x.test/a")])
        assert "[Something happened](https://x.test/a)" in text
        assert "3h 前" in text and "Wire" in text

    def test_no_news_is_reported_as_a_state_rather_than_left_blank(self):
        assert "没有消息本身也是一种状态" in self.page()
