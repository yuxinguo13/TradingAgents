"""The per-symbol page: the bear case that must never be optional.

A page assembled from the same data as the buy case is only worth reading if it
also reports what argues *against* it. :func:`risks` is generated by rule for
exactly that reason — a written bear case gets skipped on the names where it is
least convenient — so most of this file checks that each rule fires off the
number it claims to, and that an absent number produces silence rather than a
reassuring zero.
"""

import math

import pytest

from tradingagents.live import charting, deepdive
from tradingagents.live.deepdive import Bars, SymbolAnalysis, render_page, risks
from tradingagents.live.fundamentals import Fundamentals, Quarter
from tradingagents.live.zhnames import ZhNames


def bars(symbol="AAA", n=260, start=60.0, step=0.15, amp=0.03, period=17,
         volume=800_000.0):
    closes = [round((start + step * i) * (1 + amp * math.sin(i * 2 * math.pi / period)), 4)
              for i in range(n)]
    return Bars(symbol=symbol,
                dates=[f"2026-{1 + i % 12:02d}-{1 + i % 28:02d}" for i in range(n)],
                opens=list(closes),
                highs=[c * 1.015 for c in closes],
                lows=[c * 0.985 for c in closes],
                closes=closes,
                volumes=[volume] * n)


class Snap:
    def __init__(self, **kw):
        self.price = kw.get("price", 100.0)
        self.atr_pct = kw.get("atr_pct", 0.02)
        self.rsi14 = kw.get("rsi14", 55.0)
        self.vol_ratio = kw.get("vol_ratio", 1.1)
        self.ret_1m = kw.get("ret_1m", 0.05)
        self.ret_3m = kw.get("ret_3m", 0.18)


class Rec:
    symbol = "AAA"
    reference_price = 100.0
    initial_stop_price = 94.0
    stop_price = 94.0
    target_price = 118.0
    limit_price = 100.30
    shares = 160
    horizon_days = 30
    catalyst = "rank #3 on the nasdaq screen"
    catalyst_url = ""
    catalyst_source = ""
    catalyst_at = ""

    def planned_r(self):
        return 3.0

    def risk_per_share(self):
        return 6.0


class Earnings:
    error = ""
    next_date = "2026-09-12"
    last_date = "2026-06-10"
    surprise_pct = 4.2

    def __init__(self, days=8.0):
        self._days = days

    def days_to_next(self, ref=None):
        return self._days

    def reports_within(self, days, ref=None):
        return self._days <= days


class News:
    def __init__(self, title, lean="neutral", materiality=8, link="", source="Wire"):
        self.title, self.lean, self.materiality = title, lean, materiality
        self.link, self.source, self.ticker = link, source, "AAA"
        self.published = ""

    def age_hours(self, now=None):
        return 3.0


def analysis(**kw):
    b = kw.pop("bars", None) or bars()
    snap = kw.pop("snap", None) or Snap()
    a = SymbolAnalysis(symbol="AAA", zh=ZhNames(overrides={}).get("AAA", "A Company"),
                       roles=["buy"], sector="Technology", bars=b, snap=snap)
    a.trend = deepdive.build_trend(b, snap)
    for k, v in kw.items():
        setattr(a, k, v)
    return a


